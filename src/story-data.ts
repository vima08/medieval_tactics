export function storyScene(mission:string,phase:StoryPhase,choices:Record<string,string>={},language:StoryLanguage='ru'):StoryScene|undefined {
  const data=(language==='en'?ENGLISH_SCENES:scenes)[mission];if(!data)return;
  const lines=[...data[phase]];
  (language==='en'?englishConsequences:russianConsequences)(mission,phase,choices,lines);
  return{title:data.title,place:data.place,ambience:data.ambience,art:data.art,lines};
}
